def patch():
    with open(SCRAPER_PATH, 'r', encoding='utf-8') as f:
        content = f.read()

    # Find LEAGUE_TIER dict start and end
    # We'll insert new entries before the closing brace of the dict
    # Strategy: find "# T2" marker, insert T1 entries before it
    # and T2 entries after all existing T2 entries

    all_new = {**ADD_T1, **ADD_T2}

    # Check which ones already exist
    existing = set(re.findall(r"'([^']+)':\s*[12],", content))
    to_add = {k: v for k, v in all_new.items() if k not in existing}

    if not to_add:
        print("所有联赛已在白名单中，无需补丁。")
        return

    t1_new = {k: v for k, v in to_add.items() if v == 1}
    t2_new = {k: v for k, v in to_add.items() if v == 2}

    print(f"新增 T1: {len(t1_new)} 个")
    print(f"新增 T2: {len(t2_new)} 个")

    # Insert T1 entries right before "# T2" comment
    t1_str = '\n'.join(f"    '{k}': {v}," for k, v in sorted(t1_new.items()))
    t2_str = '\n'.join(f"    '{k}': {v}," for k, v in sorted(t2_new.items()))

    # Find T2 marker
    t2_marker = "    # T2"
    if t2_marker in content:
        content = content.replace(
            t2_marker,
            t1_str + '\n' + t2_marker,
            1
        )

    # Find the end of LEAGUE_TIER dict (closing brace followed by newline + EXCLUDE or other)
    # Insert T2 entries before the closing brace
    # Find the last entry before }
    # Strategy: find "}" that closes LEAGUE_TIER
    tier_start = content.find('LEAGUE_TIER = {')
    if tier_start == -1:
        print("ERROR: 找不到 LEAGUE_TIER 字典")
        return

    # Find the closing brace
    brace_count = 0
    i = tier_start + len('LEAGUE_TIER = ')
    while i < len(content):
        if content[i] == '{':
            brace_count += 1
        elif content[i] == '}':
            brace_count -= 1
            if brace_count == 0:
                break
        i += 1

    # Insert T2 entries before closing brace
    if t2_str:
        content = content[:i] + t2_str + '\n' + content[i:]

    with open(SCRAPER_PATH, 'w', encoding='utf-8') as f:
        f.write(content)

    print(f"\n✅ 补丁已应用到 {SCRAPER_PATH}")
    print(f"   新增 {len(to_add)} 个联赛 (T1:{len(t1_new)} T2:{len(t2_new)})")

    # Verify
    with open(SCRAPER_PATH, 'r', encoding='utf-8') as f:
        verify = f.read()
    now_existing = set(re.findall(r"'([^']+)':\s*[12],", verify))
    still_missing = [k for k in all_new if k not in now_existing]
    if still_missing:
        print(f"\n⚠️ 仍有 {len(still_missing)} 个未写入: {still_missing[:10]}")
    else:
        print("   验证通过 ✓")

if __name__ == '__main__':
    patch()
